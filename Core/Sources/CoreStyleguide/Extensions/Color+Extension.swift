import SwiftUI

public extension Color {
    // Accent colors used for interactive elements like buttons, icons, and highlights
    static let accentPrimary       = Color("accentPrimary")       // Primary accent color, e.g., main buttons or key interactive elements
    static let accentSecondary     = Color("accentSecondary")     // Secondary accent color, e.g., less prominent buttons or hover states

    // Background colors for the app's overall layout
    static let backgroundPrimary   = Color("backgroundPrimary")   // Main background color, e.g., app's primary screens or views
    static let backgroundSecondary = Color("backgroundSecondary") // Secondary background color, e.g., cards, modals, or contrasting sections

    // Border and divider colors
    static let borderColor         = Color("borderColor")         // Color for borders, dividers, and separators between elements

    // Error colors for states or feedback
    static let errorColor          = Color("errorColor")          // Bright error color, e.g., error messages, alerts, or invalid inputs

    // Success colors for positive states or feedback
    static let successColor        = Color("successColor")        // Bright success color, e.g., success messages, confirmation states

    // Text colors for content readability
    static let textPrimary         = Color("textPrimary")         // Primary text color, e.g., headers, main content
    static let textSecondary       = Color("textSecondary")       // Secondary text color, e.g., subtitles, secondary information
}

